# Per-user install; environments live outside the application and survive upgrades.
set -euo pipefail
source_dir="$(cd "$(dirname "$0")" && pwd)"
source_app="${1:-$source_dir/Trames.app}"
if [[ $# -eq 0 && ! -d "$source_app" && -d "$source_dir/Trames Dev.app" ]]; then source_app="$source_dir/Trames Dev.app"; fi
identifier=$(/usr/libexec/PlistBuddy -c 'Print :CFBundleIdentifier' "$source_app/Contents/Info.plist")
case "$identifier" in
  org.trames.Trames.mac) product_name="Trames"; cli_name="trames"; path_name="path.sh" ;;
  org.trames.Trames.mac.dev) product_name="Trames Dev"; cli_name="trames-dev"; path_name="path-dev.sh" ;;
  *) echo 'Source is not a recognized Trames application.' >&2; exit 1 ;;
esac
app_dir="${TRAMES_APPLICATIONS_DIR:-$HOME/Applications}"
bin_dir="${TRAMES_BIN_DIR:-$HOME/.local/bin}"
# Persist the CLI path for new login and interactive shells. A guarded source
# file makes upgrades/idempotent reinstallation independent of profile contents.
install_path() {
  [[ "${TRAMES_MODIFY_PATH:-1}" != "0" ]] || return 0
  local config_dir="${XDG_CONFIG_HOME:-$HOME/.config}/trames"
  local path_file="$config_dir/$path_name"
  local quoted_bin quoted_file profile source_line
  local profiles=()
  local shell_name="${SHELL:-/bin/zsh}"
  case "${shell_name##*/}" in
    zsh) profiles=("${ZDOTDIR:-$HOME}/.zprofile" "${ZDOTDIR:-$HOME}/.zshrc") ;;
    bash) profiles=("$HOME/.bash_profile" "$HOME/.bashrc") ;;
    sh|ksh) profiles=("$HOME/.profile") ;;
    *) printf 'Add %s to PATH in your shell configuration.\n' "$bin_dir"; return 0 ;;
  esac
  printf -v quoted_bin '%q' "$bin_dir"
  printf -v quoted_file '%q' "$path_file"
  source_line="[ ! -r $quoted_file ] || . $quoted_file"
  (
    umask 077
    mkdir -p "$config_dir"
    if [[ -e "$path_file" ]] && ! /usr/bin/grep -Fq '# Generated by Trames CLI installer' "$path_file"; then
      printf 'Preserved existing %s; add %s to PATH manually.\n' "$path_file" "$bin_dir"
      exit 0
    fi
    cat > "$path_file.tmp-$$" <<EOF
# Generated by Trames CLI installer
case ":\$PATH:" in
  *:$quoted_bin:*) ;;
  *) export PATH=$quoted_bin:"\$PATH" ;;
esac
EOF
    mv "$path_file.tmp-$$" "$path_file"
    for profile in "${profiles[@]}"; do
      mkdir -p "$(dirname "$profile")"
      if [[ ! -f "$profile" ]] || ! /usr/bin/grep -Fxq "$source_line" "$profile"; then
        printf '\n# %s CLI\n%s\n' "$product_name" "$source_line" >> "$profile"
      fi
    done
  )
  printf 'PATH configured. Open a new terminal, or run: . %s\n' "$quoted_file"
}
/usr/bin/codesign --verify --strict "$source_app"
mkdir -p "$app_dir" "$bin_dir"
stage="$app_dir/.$cli_name-install-$$.app"
dest="$app_dir/$product_name.app"
previous="$app_dir/.$cli_name-previous-$$.app"
rollback() {
  rm -rf "$stage"
  if [[ -d "$previous" && ! -e "$dest" ]]; then mv "$previous" "$dest"; fi
}
trap rollback EXIT
# Refuse CLI conflicts before replacing any installed application.
if [[ -e "$bin_dir/$cli_name" || -L "$bin_dir/$cli_name" ]]; then
  [[ -L "$bin_dir/$cli_name" && "$(readlink "$bin_dir/$cli_name")" == "$dest/Contents/MacOS/trames-mac-run" ]] || { echo "CLI path already exists: $bin_dir/$cli_name. Choose a different TRAMES_BIN_DIR." >&2; exit 1; }
fi
/usr/bin/ditto "$source_app" "$stage"
/usr/bin/codesign --verify --strict "$stage"
if [[ -e "$dest" ]]; then
  existing_identifier=$(/usr/libexec/PlistBuddy -c 'Print :CFBundleIdentifier' "$dest/Contents/Info.plist")
  [[ "$existing_identifier" == "$identifier" ]] || { echo 'Destination is not a Trames installation.' >&2; exit 1; }
  mv "$dest" "$previous"
fi
mv "$stage" "$dest"
if [[ ! -L "$bin_dir/$cli_name" ]]; then
  ln -s "$dest/Contents/MacOS/trames-mac-run" "$bin_dir/$cli_name"
fi
rm -rf "$previous"
# Existing Finder-generated Terminal launchers must use shell, because env start
# now returns after background startup. Touch only known generated launchers.
python3 - "$dest" "$product_name" <<'PYTHON'
import os,pathlib,shlex,sys
app=pathlib.Path(sys.argv[1]); product=sys.argv[2]
if 'TRAMES_HOME' not in os.environ and app.parent != pathlib.Path.home()/'Applications':
    sys.exit(0)  # A custom install must not rewrite another installation's launchers.
registry=pathlib.Path(os.environ.get('TRAMES_HOME',str(pathlib.Path.home()/'Library/Application Support'/product)))
for path in (registry/'launchers').glob('*.command'):
    text=path.read_text()
    if 'export TRAMES_HOME=' not in text or 'trames-mac-run' not in text:
        continue
    name=path.stem
    if not name or any(not (c.isascii() and (c.isalnum() or c in '-_')) for c in name):
        continue
    path.write_text('#!/bin/sh\nexport TRAMES_HOME='+shlex.quote(str(registry))+'\nexec '+shlex.quote(str(app/'Contents/MacOS/trames-mac-run'))+' -e '+shlex.quote(name)+' shell\n')
    path.chmod(0o700)
PYTHON
install_path
printf 'Installed %s\nCLI: %s/%s\nOpen %s.app for environment management.\n' "$dest" "$bin_dir" "$cli_name" "$product_name"
